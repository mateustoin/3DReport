/** Material Symbol: path na grade 960 com y de -960 a 0, por isso a translação do grupo. */
private fun symbol(name: String, path: String): ImageVector =
    ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 960f, viewportHeight = 960f)
        .group(translationY = 960f) {
            addPath(pathData = addPathNodes(path), fill = SolidColor(Color.Black))
        }
        .build()

/** Traço dos ícones desenhados aqui: 72 de 960, a espessura do peso 400 dos Material Symbols. */
private const val STROKE_WIDTH = 72f

/** Pequena DSL pros ícones desenhados à mão, na grade 960 com y de 0 (topo) a 960. */
private class CustomIconScope(private val builder: ImageVector.Builder) {
    fun stroke(path: String) {
        builder.addPath(
            pathData = addPathNodes(path),
            stroke = SolidColor(Color.Black),
            strokeLineWidth = STROKE_WIDTH,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }

    fun fill(path: String, evenOdd: Boolean = false) {
        builder.addPath(
            pathData = addPathNodes(path),
            fill = SolidColor(Color.Black),
            pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
        )
    }

    /** Borda de trás do carretel e as linhas que a ligam à frente: a parte comum às duas versões. */
    fun spoolDepth() {
        stroke("M380,140 H580 M380,820 H580")
        stroke("M580,140 A240,340 0 0,1 580,820")
    }

    /** Gabinete, carro com bico e mesa: a parte comum às duas versões da impressora. */
    fun printerCabinet() {
        stroke("M190,150 H770 V810 H190 Z")
        fill("M396,186 H564 V272 H396 Z")
        fill("M440,272 H520 L480,340 Z")
        stroke("M290,660 H670")
    }
}

private fun custom(name: String, block: CustomIconScope.() -> Unit): ImageVector {
    val builder = ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 960f, viewportHeight = 960f)
    CustomIconScope(builder).block()
    return builder.build()
}

